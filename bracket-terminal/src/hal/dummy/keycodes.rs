/// Maps a winit physical key to our `VirtualKeyCode`.
pub fn physical_key_to_virtual_keycode(key: &winit::keyboard::PhysicalKey) -> Option<VirtualKeyCode> {
    match key {
        winit::keyboard::PhysicalKey::Code(code) => keycode_to_virtual_keycode(code),
        winit::keyboard::PhysicalKey::Unidentified(_) => None,
    }
}

